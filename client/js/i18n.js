let currentLang = localStorage.getItem('ipvideo_lang') || 'fr';

function getCurrentLang() {
  return currentLang;
}

function t(key) {
  const keys = key.split('.');
  let value = TRANSLATIONS[currentLang];
  for (const k of keys) {
    value = value?.[k];
    if (value === undefined) break;
  }
  if (value === undefined && currentLang !== 'fr') {
    value = TRANSLATIONS['fr'];
    for (const k of keys) {
      value = value?.[k];
      if (value === undefined) break;
    }
  }
  return value || key;
}

function setLanguage(lang) {
  if (!['fr', 'en', 'ar'].includes(lang)) lang = 'fr';
  currentLang = lang;
  localStorage.setItem('ipvideo_lang', lang);

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // RTL for Arabic
  if (lang === 'ar') {
    document.documentElement.dir = 'rtl';
    document.body.classList.add('rtl');
  } else {
    document.documentElement.dir = 'ltr';
    document.body.classList.remove('rtl');
  }

  applyTranslations();
  updateLangSelectorUI();

  // Dispatch event for JS modules
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

function applyTranslations() {
  // Elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (!translated || translated === key) return;
    // Preserve child elements (icons, etc.) — update only the text node
    if (el.children.length > 0) {
      // Find the last text node and replace it
      const textNodes = Array.from(el.childNodes).filter(n => n.nodeType === Node.TEXT_NODE && n.textContent.trim());
      if (textNodes.length > 0) {
        textNodes[textNodes.length - 1].textContent = ' ' + translated;
      } else {
        // Fallback: append as text node
        el.appendChild(document.createTextNode(' ' + translated));
      }
    } else {
      el.textContent = translated;
    }
  });

  // Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translated = t(key);
    if (translated && translated !== key) {
      el.placeholder = translated;
    }
  });

  // Title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translated = t(key);
    if (translated && translated !== key) {
      el.title = translated;
    }
  });

  // Aria labels
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    const translated = t(key);
    if (translated && translated !== key) {
      el.setAttribute('aria-label', translated);
    }
  });

  // Meta description
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && metaDesc.hasAttribute('data-i18n')) {
    const translated = t(metaDesc.getAttribute('data-i18n'));
    if (translated && translated !== metaDesc.getAttribute('data-i18n')) {
      metaDesc.setAttribute('content', translated);
    }
  }

  // Document title
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) {
    const translated = t(titleEl.getAttribute('data-i18n'));
    if (translated && translated !== titleEl.getAttribute('data-i18n')) {
      document.title = translated;
    }
  }
}

function initLanguageSelector() {
  // Find all language selectors on the page
  document.querySelectorAll('.lang-selector').forEach(selector => {
    const btns = selector.querySelectorAll('[data-lang]');
    btns.forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const lang = btn.getAttribute('data-lang');
        if (lang) setLanguage(lang);
      });
    });
  });
  updateLangSelectorUI();
}

function updateLangSelectorUI() {
  document.querySelectorAll('.lang-selector [data-lang]').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
  });
}

// Auto-init on DOM ready
function initI18n() {
  const savedLang = localStorage.getItem('ipvideo_lang') || 'fr';
  currentLang = savedLang;

  // Set initial RTL
  if (currentLang === 'ar') {
    document.documentElement.dir = 'rtl';
    if (document.body) document.body.classList.add('rtl');
  }

  applyTranslations();
  initLanguageSelector();
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
